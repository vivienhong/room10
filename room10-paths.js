(function () {
  const currentScript = document.currentScript;
  const scriptSrc = currentScript ? currentScript.getAttribute("src") || "" : "";

  if (!window.ROOM10_ROOT) {
    window.ROOM10_ROOT = scriptSrc.replace(/room10-paths\.js(\?.*)?$/, "");
  }

  window.room10Path = function (path) {
    if (!path) return "";

    if (/^(https?:|data:|blob:|\/)/.test(path)) {
      return path;
    }

    return (window.ROOM10_ROOT || "") + path;
  };

  window.room10Page = function (key) {
    const path =
      window.ROOM10_PATHS &&
      window.ROOM10_PATHS.pages &&
      window.ROOM10_PATHS.pages[key];

    return window.room10Path(path);
  };

  window.room10Asset = function (keyPath) {
    if (!keyPath) return "";

    const keys = keyPath.split(".");
    let value = window.ROOM10_PATHS && window.ROOM10_PATHS.assets;

    for (const key of keys) {
      if (!value || !Object.prototype.hasOwnProperty.call(value, key)) {
        return "";
      }

      value = value[key];
    }

    return window.room10Path(value);
  };
})();
